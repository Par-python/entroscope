"""Walkthroughs: a synthetic frame and two bundled scikit-learn datasets.

Usage (from the repository root)::

    python -m research.feature_audit.demo --dataset {synthetic,wine,breast_cancer} \
        --output-dir PATH [--permutations B] [--subsamples S] [--overwrite]

Writes exactly two files, ``demo-<dataset>.json`` and ``demo-<dataset>.md``,
into the requested directory, and refuses to overwrite them without
``--overwrite``. Outputs hold aggregates only, never rows or category labels.
Bundled datasets load from the installed scikit-learn package. There is no
network access.
"""

